export function getSubservicesCards(serviceSlug: string): SubserviceCardItem[] {
  return subservicesCardsByService[serviceSlug] || [];
}

export function getSubserviceCard(serviceSlug: string, itemSlug: string): SubserviceCardItem | undefined {
  const cards = subservicesCardsByService[serviceSlug] || [];
  const normalizedItem = itemSlug.toLowerCase().replace(/[^a-z0-9]/g, "");
  return (
    cards.find(
      (c) =>
        c.slug === itemSlug ||
        c.id === itemSlug ||
        c.slug.toLowerCase().replace(/[^a-z0-9]/g, "") === normalizedItem ||
        c.id.toLowerCase().replace(/[^a-z0-9]/g, "") === normalizedItem
    ) ||
    cards.find(
      (c) => c.title.toLowerCase().replace(/[^a-z0-9]/g, "") === normalizedItem
    )
  );
}
